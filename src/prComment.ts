import { CatalogComparison } from './compare.js';
import { ServerBenchmarkResult } from './types.js';

function escapeMarkdown(text: string): string {
  return text.replace(/[|`*_{}[\]()#+\-.!]/g, '\\$&');
}

/**
 * Formats a clean, high-signal GitHub Pull Request comment markdown
 * comparing candidate changes against baseline.
 */
export function formatPrComment(
  comparison: CatalogComparison,
  candidateBenchmark: ServerBenchmarkResult,
  baselineBenchmark?: ServerBenchmarkResult
): string {
  const baseScore = baselineBenchmark ? baselineBenchmark.overallTQI : '—';
  const candScore = candidateBenchmark.overallTQI;
  const scoreDiff = baselineBenchmark ? candScore - baselineBenchmark.overallTQI : 0;
  const scoreSign = scoreDiff > 0 ? `+${scoreDiff} 🟢` : scoreDiff < 0 ? `${scoreDiff} 🔴` : '0 ⚪';

  const baseTokens = baselineBenchmark ? `${baselineBenchmark.totalTokens} tok` : '—';
  const candTokens = `${candidateBenchmark.totalTokens} tok`;
  const tokenDiff = baselineBenchmark ? candidateBenchmark.totalTokens - baselineBenchmark.totalTokens : 0;
  const tokenSign = tokenDiff < 0 ? `${tokenDiff} tok ⚡` : tokenDiff > 0 ? `+${tokenDiff} tok ⚠️` : '0 tok';

  const breakingCount = comparison.breakingChanges.length;
  const breakingBadge = breakingCount === 0 ? '0 ✅' : `${breakingCount} 🚨 BREAKING`;

  let md = '## 📊 Model Context Protocol (MCP) Tool Benchmark — PR Summary\n\n';

  md += '| Metric | Baseline | Candidate | Change |\n';
  md += '|:---|:---:|:---:|:---:|\n';
  md += `| **Overall TQI Score** | ${baseScore} | **${candScore}/100** (\`${candidateBenchmark.grade}\`) | ${scoreSign} |\n`;
  md += `| **Context Token Footprint** | ${baseTokens} | **${candTokens}** | ${tokenSign} |\n`;
  md += `| **Total Tools Count** | ${baselineBenchmark ? baselineBenchmark.toolsAnalyzed : '—'} | ${candidateBenchmark.toolsAnalyzed} | ${comparison.addedTools.length - comparison.removedTools.length >= 0 ? '+' : ''}${comparison.addedTools.length - comparison.removedTools.length} |\n`;
  md += `| **Breaking Changes** | — | — | **${breakingBadge}** |\n\n`;

  if (breakingCount > 0) {
    md += '### 🚨 Breaking Changes Detected\n\n';
    for (const change of comparison.breakingChanges) {
      if (change.kind === 'tool-removed') {
        md += `* ❌ **Tool Removed:** \`${change.toolName}\` was deleted from the catalog.\n`;
      } else if (change.kind === 'required-input-added') {
        md += `* ⚠️ **Required Input Added:** \`${change.toolName}\` now requires \`${change.property}\`.\n`;
      }
    }
    md += '\n';
  }

  md += '### 📦 Catalog Evolution\n\n';
  md += `* **Added Tools:** ${comparison.addedTools.length > 0 ? comparison.addedTools.map(t => `\`${t}\``).join(', ') : '_None_'}\n`;
  md += `* **Removed Tools:** ${comparison.removedTools.length > 0 ? comparison.removedTools.map(t => `\`${t}\``).join(', ') : '_None_'}\n`;
  md += `* **Modified Tools:** ${comparison.changedTools.length > 0 ? comparison.changedTools.map(t => `\`${t.toolName}\` (${t.fields.join(', ')})`).join(', ') : '_None_'}\n\n`;

  if (comparison.newDiagnostics.length > 0 || comparison.resolvedDiagnostics.length > 0) {
    md += '<details>\n<summary><b>🔍 View Diagnostic Changes (Click to expand)</b></summary>\n<br>\n\n';
    if (comparison.newDiagnostics.length > 0) {
      md += '#### ⚠️ New Findings\n\n';
      for (const diag of comparison.newDiagnostics) {
        md += `* **[${diag.severity.toUpperCase()}]** \`${diag.toolName}\` (${diag.path || '/'}): ${diag.message}. _Suggestion: ${diag.suggestion}_\n`;
      }
      md += '\n';
    }
    if (comparison.resolvedDiagnostics.length > 0) {
      md += '#### ✅ Resolved Findings\n\n';
      for (const diag of comparison.resolvedDiagnostics) {
        md += `* ~**[${diag.severity.toUpperCase()}]** \`${diag.toolName}\` (${diag.path || '/'}): ${diag.message}~\n`;
      }
      md += '\n';
    }
    md += '</details>\n\n';
  }

  md += '> _Generated by [mcp-benchmark](https://github.com/yunusarda-sudo/mcp-benchmark) — Deterministic quality benchmark & linter for MCP tools._\n';

  return md;
}
