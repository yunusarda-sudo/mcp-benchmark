// Pure helpers that turn benchmarked registry entries into README sections,
// LEADERBOARD.md and the site data. No file system or network access here, so
// the output is a deterministic function of the input rows.
//
// Every server name, title and URL comes from third-party registry data and is
// treated as untrusted: text is escaped for Markdown/HTML and links are https only.

export const NEW_RELEASES_LIMIT = 10;
export const LEADERBOARD_SUMMARY_LIMIT = 15;

const ISO_DATE = /^\d{4}-\d{2}-\d{2}T/;

/** Escapes untrusted text for inline Markdown, including table cells (no HTML, links, emphasis or pipes). */
export function escapeMarkdown(value) {
  return String(value ?? '')
    .replace(/[\u0000-\u001f\u007f\u2028\u2029]/g, ' ')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/([\\`*_[\]()|!#~])/g, '\\$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Escapes untrusted text for HTML text and attribute contexts. */
export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Returns a normalized https URL safe to place inside a Markdown link target, or null. */
export function safeHttpsUrl(value) {
  if (typeof value !== 'string' || value.length === 0) return null;
  let url;
  try {
    url = new URL(value);
  } catch {
    return null;
  }
  if (url.protocol !== 'https:' || url.username || url.password) return null;
  return url.href.replace(/[()<>\s"'`[\]]/g, ch => `%${ch.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0')}`);
}

/** Registry file slugs are produced by the sync; anything else is not linked. */
function safeSlug(slug) {
  return typeof slug === 'string' && /^[a-z0-9][a-z0-9-]*$/.test(slug) ? slug : null;
}

function dateOnly(iso) {
  return typeof iso === 'string' && ISO_DATE.test(iso) ? iso.slice(0, 10) : '';
}

/**
 * The most recently published registry servers, newest first.
 * Rows without a valid ISO publishedAt (for example manual entries) are skipped.
 * Ties keep the input order (Array#sort is stable), so pass rows in leaderboard order.
 */
export function selectNewReleases(rows, limit = NEW_RELEASES_LIMIT) {
  return rows
    .filter(row => typeof row.publishedAt === 'string' && ISO_DATE.test(row.publishedAt) && !Number.isNaN(Date.parse(row.publishedAt)))
    .map((row, index) => ({ row, index, time: Date.parse(row.publishedAt) }))
    .sort((a, b) => b.time - a.time || a.index - b.index)
    .slice(0, Math.max(0, limit))
    .map(item => item.row);
}

function serverCell(row) {
  const title = row.title && row.title !== row.name ? row.title : row.name;
  const label = escapeMarkdown(title);
  const repository = safeHttpsUrl(row.repository);
  const named = repository ? `[**${label}**](${repository})` : `**${label}**`;
  const id = title !== row.name ? ` · \`${String(row.name).replace(/[`|\\]/g, '')}\`` : '';
  const manual = row.sourceType === 'manual' ? ' (manual entry)' : '';
  return `${named}${id}${manual}`;
}

function sourceCell(row, linkPrefix) {
  const slug = safeSlug(row.slug);
  return slug ? `[json](${linkPrefix}registry/servers/${slug}.json)` : '';
}

export function renderNewReleasesMarkdown(rows, { linkPrefix = '' } = {}) {
  if (rows.length === 0) return '_No registry servers with a publish date are listed yet._';
  const lines = [
    '| Published | Server | Grade | TQI | Tools | Data |',
    '|:---|:---|:---:|---:|---:|:---:|',
    ...rows.map(
      r => `| ${dateOnly(r.publishedAt)} | ${serverCell(r)} | \`${escapeMarkdown(r.grade)}\` | ${Number(r.tqi)} | ${Number(r.toolsCount)} | ${sourceCell(r, linkPrefix)} |`
    ),
  ];
  return lines.join('\n');
}

export function renderLeaderboardSummaryMarkdown(rows, { limit = LEADERBOARD_SUMMARY_LIMIT, linkPrefix = '' } = {}) {
  if (rows.length === 0) return '_No servers with verified tool data yet._';
  const lines = [
    '| # | Server | Grade | TQI | Tools | Tokens/tool | Data |',
    '|---:|:---|:---:|---:|---:|---:|:---:|',
    ...rows
      .slice(0, limit)
      .map(
        (r, i) =>
          `| ${i + 1} | ${serverCell(r)} | \`${escapeMarkdown(r.grade)}\` | ${Number(r.tqi)} | ${Number(r.toolsCount)} | ${Number(r.tokensPerTool)} | ${sourceCell(r, linkPrefix)} |`
      ),
  ];
  return lines.join('\n');
}

export function renderLeaderboardFile(rows, syncSummaryMarkdown) {
  const header = [
    '# MCP Registry Leaderboard',
    '',
    '<!-- Generated by scripts/generate-ecosystem-artifacts.mjs. Do not edit by hand. -->',
    '',
    'Real `tools/list` output from auth-free remote servers in the [official MCP Registry](https://registry.modelcontextprotocol.io), scored by [mcp-benchmark](README.md). This is a partial sample of the registry; see [Methodology](README.md#methodology-and-data) for what is and is not covered.',
    '',
    syncSummaryMarkdown,
    '',
    'Ranked by TQI, then token efficiency, then name. **Data** links to the stored entry with its provenance (registry name, version, remote URL, fetch time, SHA-256 of the tools).',
    '',
    '| # | Server | Grade | TQI | Tools | Strictness | Density | Efficiency | Tokens/tool | Published | Data |',
    '|---:|:---|:---:|---:|---:|---:|---:|---:|---:|:---|:---:|',
  ];
  const body = rows.map(
    (r, i) =>
      `| ${i + 1} | ${serverCell(r)} | \`${escapeMarkdown(r.grade)}\` | ${Number(r.tqi)} | ${Number(r.toolsCount)} | ${Number(r.strictness)}% | ${Number(r.density)}% | ${Number(r.efficiency)}% | ${Number(r.tokensPerTool)} | ${dateOnly(r.publishedAt)} | ${sourceCell(r, '')} |`
  );
  return `${[...header, ...body].join('\n')}\n`;
}

/** Replaces the text between two markers; returns the content unchanged when either is missing. */
export function replaceBetween(content, start, end, replacement) {
  const from = content.indexOf(start);
  const to = content.indexOf(end);
  if (from === -1 || to < from) return content;
  return `${content.slice(0, from + start.length)}\n${replacement}\n${content.slice(to)}`;
}
